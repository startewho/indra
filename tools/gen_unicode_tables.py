"""Generate the Unicode tables .NET does not expose: bidi class and East Asian Width.

    python tools/gen_unicode_tables.py

Writes dotnet/src/IndraOcr/Numerics/UnicodeTables.g.cs from Python's unicodedata,
which is the reference the port must agree with (see rtl.py, order_post.py).

Bidi classes kept: L=1, R=2, AL=3, EN=4, AN=5; everything else (including
unassigned, whose bidi class is "") is 0.  Wide ranges are the code points whose
East_Asian_Width is W or F.
"""

from __future__ import annotations

import unicodedata as ud
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "dotnet" / "src" / "IndraOcr" / "Numerics" / "UnicodeTables.g.cs"
MAX = 0x110000
BIDI = {"L": 1, "R": 2, "AL": 3, "EN": 4, "AN": 5}


def bidi_ranges() -> list[tuple[int, int, int]]:
    out: list[tuple[int, int, int]] = []
    start, cur = 0, -1
    for cp in range(MAX):
        c = chr(cp)
        cls = 0 if 0xD800 <= cp <= 0xDFFF else BIDI.get(ud.bidirectional(c), 0)
        if cls != cur:
            if cur >= 0:
                out.append((start, cp - 1, cur))
            start, cur = cp, cls
    out.append((start, MAX - 1, cur))
    # Keep only non-default ranges: most code points are bidi class 0 here.
    return [r for r in out if r[2] != 0]


def wide_ranges() -> list[tuple[int, int]]:
    out: list[tuple[int, int]] = []
    start = None
    for cp in range(MAX):
        wide = 0xD800 <= cp <= 0xDFFF or ud.east_asian_width(chr(cp)) in ("W", "F")
        if wide and start is None:
            start = cp
        elif not wide and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, MAX - 1))
    return out


def emit(name: str, rows: list, width: int) -> str:
    per_line = 6 if width == 3 else 8
    lines = []
    for i in range(0, len(rows), per_line):
        chunk = rows[i : i + per_line]
        if width == 3:
            body = ", ".join(f"0x{a:X}, 0x{b:X}, {v}" for a, b, v in chunk)
        else:
            body = ", ".join(f"0x{a:X}, 0x{b:X}" for a, b in chunk)
        lines.append("        " + body + ",")
    return "\n".join(lines)


def main() -> int:
    bidi = bidi_ranges()
    wide = wide_ranges()
    text = f"""// <auto-generated>
// Generated by tools/gen_unicode_tables.py from Python {ud.unidata_version} unicodedata.
// Do not edit by hand.  Bidi classes: L=1, R=2, AL=3, EN=4, AN=5, other=0.
// </auto-generated>

namespace IndraOcr.Numerics;

internal static class UnicodeTables
{{
    /// <summary>Sorted ranges: start, end, bidi class (0 when absent).</summary>
    internal static readonly int[] BidiRanges =
    {{
{emit("bidi", bidi, 3)}
    }};

    /// <summary>Sorted ranges of code points whose East Asian Width is W or F.</summary>
    internal static readonly int[] WideRanges =
    {{
{emit("wide", wide, 2)}
    }};
}}
"""
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT} ({len(bidi)} bidi ranges, {len(wide)} wide ranges)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
